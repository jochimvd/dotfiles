local mode = require("conf.binds.modes")

mode.universal("SUPER + SPACE", hl.dsp.exec_cmd("varde launcher"), "Launcher")
mode.universal("SUPER + V", hl.dsp.exec_cmd("varde clipboard"), "Clipboard")
mode.universal("SUPER + B", hl.dsp.exec_cmd("dot-menu-keybinds"), "Keybinding help")

mode.enter("SUPER + X", "Session")
mode.define("Session", function(bind)
    bind("L", hl.dsp.exec_cmd("dot-cmd-lockscreen"), "Lock")
    -- The wiki warns against dpms straight from a keybind, so it runs from a timer.
    bind("D", function()
        hl.timer(function()
            hl.dispatch(hl.dsp.dpms({ action = "off" }))
        end, { timeout = 500, type = "oneshot" })
    end, "Display off")
    bind("S", hl.dsp.exec_cmd("systemctl suspend"), "Suspend", { release = true })
    bind("P", hl.dsp.exec_cmd("dot-menu-power"), "Power menu")
end)

mode.enter("SUPER + N", "Notifications")
mode.define("Notifications", function(bind)
    bind("N", hl.dsp.exec_cmd("varde notifications invoke"), "Open latest")
    bind("A", hl.dsp.exec_cmd("varde notifications actions"), "Actions")
    bind("D", hl.dsp.exec_cmd("varde notifications dismiss"), "Dismiss latest", { stay = true })
    bind("SHIFT + D", hl.dsp.exec_cmd("varde notifications clear"), "Dismiss all")
    bind("C", hl.dsp.exec_cmd("varde notifications"), "Notification center")
    bind("Z", hl.dsp.exec_cmd("varde notifications dnd"), "Do not disturb")
end)

mode.universal("PRINT", hl.dsp.exec_cmd("dot-cmd-screenshot"), "Screenshot")
mode.universal("SHIFT + PRINT", hl.dsp.exec_cmd("dot-cmd-screenshot smart clipboard"), "Copy screenshot")

mode.enter("SUPER + C", "Capture")
mode.define("Capture", function(bind)
    bind("S", hl.dsp.exec_cmd("dot-cmd-screenshot"), "Screenshot")
    bind("Y", hl.dsp.exec_cmd("dot-cmd-screenshot smart clipboard"), "Copy screenshot")
    bind("R", hl.dsp.exec_cmd("dot-cmd-screenshot region"), "Region")
    bind("W", hl.dsp.exec_cmd("dot-cmd-screenshot windows"), "Window")
    bind("F", hl.dsp.exec_cmd("dot-cmd-screenshot fullscreen"), "Display")
    bind("V", hl.dsp.exec_cmd("dot-cmd-screenrecord"), "Record region / stop")
    bind("SHIFT + V", hl.dsp.exec_cmd("dot-cmd-screenrecord output"), "Record display / stop")
    bind("P", hl.dsp.exec_cmd("pkill hyprpicker || hyprpicker -a"), "Color picker")
end)
